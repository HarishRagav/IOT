from machine import Pin, I2C
import sh1106
import time
import random


# =========================================================
# OLED SETUP
# =========================================================

i2c = I2C(
    0,
    sda=Pin(20),
    scl=Pin(21),
    freq=100000
)

oled = sh1106.SH1106_I2C(
    128,
    64,
    i2c,
    addr=0x3C
)


# =========================================================
# TEXT
# =========================================================

TOP_TEXT = "ITS"
BOTTOM_TEXT = "HAMMER TIME"


# =========================================================
# DRAW TEXT
# =========================================================

def draw_text():

    oled.fill(0)

    # -----------------------------
    # ITS
    # -----------------------------

    x1 = (
        128 -
        len(TOP_TEXT) * 8
    ) // 2

    oled.text(
        TOP_TEXT,
        x1,
        16
    )

    # -----------------------------
    # HAMMER TIME
    # -----------------------------

    x2 = (
        128 -
        len(BOTTOM_TEXT) * 8
    ) // 2

    oled.text(
        BOTTOM_TEXT,
        x2,
        32
    )


# =========================================================
# IMPACT EFFECT
# =========================================================

def draw_impact(frame):

    draw_text()

    # =====================================================
    # FRAME 0
    # Small burst
    # =====================================================

    if frame == 0:

        oled.line(
            29, 22,
            21, 18,
            1
        )

        oled.line(
            99, 22,
            107, 18,
            1
        )

        oled.line(
            29, 46,
            21, 50,
            1
        )

        oled.line(
            99, 46,
            107, 50,
            1
        )


    # =====================================================
    # FRAME 1
    # Bigger burst
    # =====================================================

    elif frame == 1:

        oled.line(
            26, 21,
            15, 13,
            1
        )

        oled.line(
            102, 21,
            113, 13,
            1
        )

        oled.line(
            26, 48,
            15, 55,
            1
        )

        oled.line(
            102, 48,
            113, 55,
            1
        )

        # Top rays

        oled.line(
            43, 13,
            39, 6,
            1
        )

        oled.line(
            85, 13,
            89, 6,
            1
        )


    # =====================================================
    # FRAME 2
    # Maximum burst
    # =====================================================

    elif frame == 2:

        oled.line(
            22, 20,
            7, 10,
            1
        )

        oled.line(
            106, 20,
            121, 10,
            1
        )

        oled.line(
            22, 49,
            7, 58,
            1
        )

        oled.line(
            106, 49,
            121, 58,
            1
        )

        # Top

        oled.line(
            43, 12,
            38, 3,
            1
        )

        oled.line(
            85, 12,
            90, 3,
            1
        )


    # =====================================================
    # FRAME 3
    # Fade away
    # =====================================================

    elif frame == 3:

        oled.line(
            18, 24,
            11, 21,
            1
        )

        oled.line(
            110, 24,
            117, 21,
            1
        )

        oled.line(
            18, 45,
            11, 48,
            1
        )

        oled.line(
            110, 45,
            117, 48,
            1
        )


# =========================================================
# MAIN LOOP
# =========================================================

while True:

    # -----------------------------------------------------
    # Clean text
    # -----------------------------------------------------

    draw_text()

    oled.show()

    time.sleep(
        random.uniform(
            1.2,
            2.5
        )
    )


    # -----------------------------------------------------
    # IMPACT / BONK EFFECT
    # -----------------------------------------------------

    for frame in range(4):

        draw_impact(frame)

        oled.show()

        time.sleep(0.065)


    # -----------------------------------------------------
    # Return to clean
    # -----------------------------------------------------

    draw_text()

    oled.show()

    time.sleep(
        random.uniform(
            0.7,
            1.5
        )
    )
